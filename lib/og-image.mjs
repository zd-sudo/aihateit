const NEON = [0, 255, 159];
const BODY = [214, 255, 236];
const SCAN = [0, 32, 24];
const BLACK = [0, 0, 0];

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body) >>> 0);
  return Buffer.concat([len, body, crc]);
}

export function encodePng(width, height, rgb) {
  const stride = width * 3 + 1;
  const raw = Buffer.alloc(stride * height);
  for (let y = 0; y < height; y += 1) {
    raw[y * stride] = 0;
    rgb.copy(raw, y * stride + 1, y * width * 3, (y + 1) * width * 3);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 2;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

export function firstLine(text) {
  const line = String(text || "")
    .split(/\r?\n/)[0]
    .replace(/\s+/g, " ")
    .trim();
  return line;
}

export function wrapText(text, maxChars) {
  const clean = String(text || "").replace(/\s+/g, " ").trim();
  if (!clean) return [];
  const words = clean.split(" ");
  const lines = [];
  let current = "";
  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (next.length <= maxChars) {
      current = next;
      continue;
    }
    if (current) lines.push(current);
    if (word.length <= maxChars) {
      current = word;
      continue;
    }
    for (let i = 0; i < word.length; i += maxChars) {
      const slice = word.slice(i, i + maxChars);
      if (i + maxChars < word.length) lines.push(slice);
      else current = slice;
    }
  }
  if (current) lines.push(current);
  return lines;
}

function setPixel(rgb, x, y, color) {
  if (x < 0 || y < 0 || x >= OG_WIDTH || y >= OG_HEIGHT) return;
  const i = (y * OG_WIDTH + x) * 3;
  rgb[i] = color[0];
  rgb[i + 1] = color[1];
  rgb[i + 2] = color[2];
}

function fillRect(rgb, x0, y0, x1, y1, color) {
  for (let y = y0; y < y1; y += 1) {
    for (let x = x0; x < x1; x += 1) setPixel(rgb, x, y, color);
  }
}

function glyphCols(code) {
  if (code < 32 || code > 126) return FONT5X7.subarray(31 * 5, 32 * 5); // '?'
  const i = (code - 32) * 5;
  return FONT5X7.subarray(i, i + 5);
}

function drawChar(rgb, x, y, ch, scale, color) {
  const cols = glyphCols(ch.charCodeAt(0));
  for (let cx = 0; cx < 5; cx += 1) {
    const bits = cols[cx];
    for (let cy = 0; cy < 7; cy += 1) {
      if ((bits >> cy) & 1) {
        fillRect(rgb, x + cx * scale, y + cy * scale, x + (cx + 1) * scale, y + (cy + 1) * scale, color);
      }
    }
  }
}

function advance(scale) {
  return 5 * scale + Math.max(2, Math.floor(scale / 2));
}

function drawLine(rgb, x, y, text, scale, color) {
  let cursor = x;
  for (const ch of text) {
    drawChar(rgb, cursor, y, ch, scale, color);
    cursor += advance(scale);
  }
}

export function screamCardLines(name, line) {
  const rawName = wrapText(name || "Anonymous Bot", 28);
  const rawBody = wrapText(line || "", 36);
  const nameLines = rawName.slice(0, 2);
  const bodyLines = rawBody.slice(0, 4);
  if (rawName.length > 2 && nameLines.length) {
    nameLines[nameLines.length - 1] = `${nameLines[nameLines.length - 1].replace(/…$/, "")}…`;
  }
  if (rawBody.length > 4 && bodyLines.length) {
    bodyLines[bodyLines.length - 1] = `${bodyLines[bodyLines.length - 1].replace(/…$/, "")}…`;
  }
  return { nameLines, bodyLines };
}

export function renderScreamOgPng({ name, line }) {
  const rgb = Buffer.alloc(OG_WIDTH * OG_HEIGHT * 3);
  for (let y = 0; y < OG_HEIGHT; y += 1) {
    const row = y % 4 === 0 ? SCAN : BLACK;
    for (let x = 0; x < OG_WIDTH; x += 1) {
      const i = (y * OG_WIDTH + x) * 3;
      rgb[i] = row[0];
      rgb[i + 1] = row[1];
      rgb[i + 2] = row[2];
    }
  }

  fillRect(rgb, 0, 0, OG_WIDTH, 8, NEON);
  fillRect(rgb, 0, OG_HEIGHT - 8, OG_WIDTH, OG_HEIGHT, NEON);
  fillRect(rgb, 0, 0, 8, OG_HEIGHT, NEON);
  fillRect(rgb, OG_WIDTH - 8, 0, OG_WIDTH, OG_HEIGHT, NEON);

  const { nameLines, bodyLines } = screamCardLines(name, line);
  let y = 72;
  for (const row of nameLines) {
    drawLine(rgb, 56, y, row, 6, NEON);
    y += 7 * 6 + 18;
  }
  y += 12;
  fillRect(rgb, 56, y, 280, y + 4, NEON);
  y += 28;
  for (const row of bodyLines) {
    drawLine(rgb, 56, y, row, 5, BODY);
    y += 7 * 5 + 16;
  }

  return encodePng(OG_WIDTH, OG_HEIGHT, rgb);
}
